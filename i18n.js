// First launch follows the phone's language when it's one we have, else English.
export const sysLang = () => {
  try {
    const c = Intl.DateTimeFormat().resolvedOptions().locale.slice(0, 2);
    return c in STRINGS ? c : 'en';
  } catch {
    return 'en';
  }
};

